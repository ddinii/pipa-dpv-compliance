def _catalog(notes: list[tuple[str, str, str]]) -> str:
    lines = []
    for fact_id, description, value_type in notes:
        prop = FACT_SPECS[fact_id].ontology_property or "null"
        lines.append(
            f"  - {fact_id} | {description} | ontology_property={prop} | 값 타입={value_type}"
        )
    return "\n".join(lines)


